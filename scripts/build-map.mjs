// Builds js/map-data.js from a Karnataka district GeoJSON.
// Usage: node scripts/build-map.mjs path/to/karnataka.geojson
// Source data: https://github.com/udit-001/india-maps-data (2011 census districts)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const src = process.argv[2];
if (!src) {
  console.error("Usage: node scripts/build-map.mjs <karnataka.geojson>");
  process.exit(1);
}
const geo = JSON.parse(readFileSync(src, "utf8"));

// Loose cultural grouping of districts into the app's zones.
const ZONE_OF = {
  "Mysuru": "south", "Mandya": "south", "Chamarajanagara": "south",
  "Bengaluru Urban": "south", "Bengaluru Rural": "south", "Ramanagara": "south",
  "Kolar": "south", "Chikkaballapura": "south", "Tumakuru": "south",
  "Chitradurga": "south", "Davanagere": "south",
  "Chikkamagaluru": "malnad", "Shivamogga": "malnad", "Hassan": "malnad",
  "Kodagu": "malnad", "Uttara Kannada": "malnad",
  "Udupi": "coast", "Dakshina Kannada": "coast",
  "Belagavi": "north", "Dharwad": "north", "Gadag": "north", "Haveri": "north",
  "Bagalkote": "north", "Vijayapura": "north",
  "Kalaburagi": "kalyana", "Bidar": "kalyana", "Raichur": "kalyana",
  "Koppal": "kalyana", "Ballari": "kalyana", "Yadgir": "kalyana",
};

// Find bounds.
let minLng = Infinity, maxLng = -Infinity, minLat = Infinity, maxLat = -Infinity;
const rings = (g) => (g.type === "Polygon" ? [g.coordinates] : g.coordinates);
for (const f of geo.features) {
  for (const poly of rings(f.geometry)) for (const ring of poly) for (const [x, y] of ring) {
    minLng = Math.min(minLng, x); maxLng = Math.max(maxLng, x);
    minLat = Math.min(minLat, y); maxLat = Math.max(maxLat, y);
  }
}

// Equirectangular projection, corrected for latitude. Fine for a state-sized area.
const WIDTH = 600;
const PAD = 12;
const lat0 = (minLat + maxLat) / 2;
const kx = Math.cos((lat0 * Math.PI) / 180);
const scale = (WIDTH - PAD * 2) / ((maxLng - minLng) * kx);
const HEIGHT = Math.round((maxLat - minLat) * scale + PAD * 2);
const proj = { minLng, maxLat, kx, scale, pad: PAD };
const project = ([lng, lat]) => [
  PAD + (lng - minLng) * kx * scale,
  PAD + (maxLat - lat) * scale,
];

// Path with light simplification: drop points closer than MIN px to the last kept one.
const MIN = 0.9;
function ringPath(ring) {
  const pts = [];
  for (const c of ring) {
    const p = project(c);
    const last = pts[pts.length - 1];
    if (!last || Math.hypot(p[0] - last[0], p[1] - last[1]) >= MIN) pts.push(p);
  }
  if (pts.length < 3) return "";
  return "M" + pts.map(([x, y]) => `${x.toFixed(1)},${y.toFixed(1)}`).join("L") + "Z";
}

const districts = geo.features.map((f) => {
  const name = f.properties.district;
  const d = rings(f.geometry).flatMap((poly) => poly.map(ringPath)).join("");
  if (!ZONE_OF[name]) console.warn("No zone for", name);
  return { name, zone: ZONE_OF[name] || "south", d };
});

const out = `// Generated by scripts/build-map.mjs. Do not edit by hand.
// District boundaries: udit-001/india-maps-data (2011 census), simplified.
export const MAP = ${JSON.stringify({ width: WIDTH, height: HEIGHT, proj, districts })};

export function projectPoint(lng, lat) {
  const { minLng, maxLat, kx, scale, pad } = MAP.proj;
  return [pad + (lng - minLng) * kx * scale, pad + (maxLat - lat) * scale];
}
`;
const here = dirname(fileURLToPath(import.meta.url));
const target = join(here, "..", "js", "map-data.js");
writeFileSync(target, out);
console.log(`Wrote ${target}: ${districts.length} districts, ${WIDTH}x${HEIGHT}, ${(out.length / 1024).toFixed(0)} KB`);
